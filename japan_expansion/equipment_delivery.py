"""R11.1: explicit paid-unit strength and usable deployment facilities.

Apply after regional_content and final_event_integrity, before compilation.
Named strength restoration only targets newly created divisions with unique
formation names, checked against the clean scenario and unit-name lists.
"""
from copy import deepcopy
from catalog import EVENTS, cmd
import regional_content
import specialist_units as sp

REPORT = {}
DOCUMENTED_NEW_COMMANDS = {'damage_division'}
FORMATION_NAMES = {
    'cn_shanghai_holding_finish_0': ('Shanghai Port Defence Division', 'Wusong Defence Division'),
    'cn_shanghai_holding_finish_1': ('Shanghai Expeditionary Infantry',),
    'cn_wuhan_choice_finish_0': ('Wuhan Mountain Division', 'Yangtze Mountain Division'),
    'ph_manila_air_finish_0': ('Manila Fighter Wing', 'Luzon Fighter Wing'),
    'ph_manila_air_finish_1': ('Manila Naval Air Wing', 'Luzon Naval Air Wing'),
    'ph_island_agreement_finish_0': ('Philippine Expeditionary Division', 'Luzon Expeditionary Division'),
    'in_java_shipyards_finish_0': ('Soerabaja Escort Flotilla', 'Java Escort Flotilla'),
    'in_java_shipyards_finish_1': ('Soerabaja Patrol Cruiser',),
}


def _quote(text):
    return '"' + text + '"'


def _command(node):
    # All nodes rewritten here contain scalar add_corps/add_division fields.
    return ' '.join(k + ' = ' + (_quote(v) if k == 'which' else v) for k, v in node)


def apply():
    if REPORT.get('applied'):
        return REPORT
    from build import serialise
    by = {e.key: e for e in EVENTS}
    deliveries = []
    all_names = set()
    for programme in regional_content.PROGRAMMES:
        key = programme['key']
        offer = by[key]
        touched = False
        facilities = set()
        for i, option in enumerate(programme['choices']):
            finish = by[f'{key}_finish_{i}']
            action = finish.actions[0]
            parsed = [sp.parse(c) for c in action.commands]
            divisions = [(j, c) for j, c in enumerate(parsed) if sp.get(c, 'type') == 'add_division']
            if not divisions:
                continue
            corps = [c for c in parsed if sp.get(c, 'type') == 'add_corps']
            if len(corps) != 1:
                raise ValueError('Expected one explicit corps for paid package ' + finish.key)
            branch = sp.get(corps[0], 'value')
            site = int(sp.get(corps[0], 'where'))
            if branch not in {'land', 'air', 'naval'}:
                raise ValueError('Unsupported corps branch ' + str(branch))
            facility = {'air': 'air_base', 'naval': 'naval_base'}.get(branch)
            facility_gate = ''
            if facility:
                facilities.add(facility)
                facility_gate = f'building = {{ province = {site} type = {facility} value = 1 when = now }}'
                offer.actions[i].gate += ' ' + facility_gate
                option['gate'] += ' ' + facility_gate
                action.gate += ' ' + facility_gate
                # The refund must cover the added facility failure as well as
                # every original validity condition. Its pending/choice/age
                # predicate stays exactly as generated by the final flow pass.
                refund = sp.parse(finish.actions[1].gate)
                validity = [sp.get(v, 'AND') for k, v in refund
                            if k == 'NOT' and isinstance(v, list) and sp.get(v, 'AND') is not None]
                if len(validity) != 1:
                    raise ValueError('Ambiguous refund validity in ' + finish.key)
                validity[0].extend(sp.parse(facility_gate))
                finish.actions[1].gate = serialise(refund)
            names, heals = [], []
            if len(FORMATION_NAMES[finish.key]) != len(divisions):
                raise ValueError('Formation-name count does not match paid package')
            for ordinal, (index, node) in enumerate(divisions, 1):
                if sp.get(node, 'where') is not None:
                    raise ValueError('Paid award unexpectedly has a brigade/damaged-unit argument: ' + finish.key)
                name = FORMATION_NAMES[finish.key][ordinal - 1]
                if name in all_names:
                    raise ValueError('Duplicate paid-unit target name')
                all_names.add(name)
                sp.replace(node, 'which', name)
                action.commands[index] = _command(node)
                names.append(name)
                # Engine docs: negative damage is strength gain, expressed as
                # percent of max STR and clamped to the existing unit cap.
                heals.append(cmd('damage_division', which=_quote(name), value='JAP', where=-100))
            last = divisions[-1][0] + 1
            action.commands[last:last] = heals
            # Keep programme metadata consistent with the actual final award.
            option['awards'] = action.commands[:last + len(heals)]
            note = (' New formations are brought to their existing allowed maximum '
                    'strength on delivery. Organisation follows normal deployment '
                    'and reorganisation; later damage and mobilisation still apply.')
            if facility:
                note += (' A current ' + ('airfield' if branch == 'air' else 'naval base')
                         + ' of at least level one is required both when funding and '
                         'when receiving this package; failure returns every paid input.')
            finish.desc += note
            deliveries.append({'offer': key, 'finish': finish.key, 'id': finish.id,
                               'choice': i, 'branch': branch, 'site': site,
                               'facility_gate': facility_gate, 'unit_names': names,
                               'manpower_reserved': option['mp'], 'count': len(divisions)})
            touched = True
        if touched:
            offer.desc += ('\n\nNew formations arrive at their existing allowed maximum '
                           'strength. Organisation follows normal deployment, and '
                           'later damage or mobilisation can still reduce strength.')
            if facilities:
                offer.desc += (' A current ' + ('airfield' if 'air_base' in facilities else 'naval base')
                               + ' of at least level one is required at funding and '
                               'receipt; losing it returns the full bill.')
    american = []
    for key, prefix in (('usc_coast_response', 'Western Reserve'),
                        ('usc_inland_response', 'Central Reserve')):
        e = by[key]
        for action_index, action in enumerate(e.actions):
            nodes = [sp.parse(c) for c in action.commands]
            additions = [(j, c) for j, c in enumerate(nodes) if sp.get(c, 'type') == 'add_division']
            if not additions:
                continue
            corps = [(j, c) for j, c in enumerate(nodes) if sp.get(c, 'type') == 'add_corps']
            if len(corps) != 1:
                raise ValueError('Expected one American reserve staging corps')
            corps_index, corps_node = corps[0]
            site = int(sp.get(corps_node, 'where'))
            sp.replace(corps_node, 'which', sp.get(corps_node, 'which').replace('Continental Reserve', prefix, 1))
            action.commands[corps_index] = serialise(corps_node)
            heals, names = [], set()
            for index, node in additions:
                if sp.get(node, 'where') is not None or not sp.get(node, 'trigger'):
                    raise ValueError('Unexpected American reserve model/brigade contract')
                name = sp.get(node, 'which').replace('Continental Reserve', prefix, 1)
                sp.replace(node, 'which', name)
                action.commands[index] = serialise(node)
                healing = [('trigger', deepcopy(sp.get(node, 'trigger'))),
                           ('type', 'damage_division'), ('which', name),
                           ('value', 'USA'), ('where', '-100')]
                heals.append(serialise(healing))
                names.add(name)
            insert = additions[-1][0] + 1
            action.commands[insert:insert] = heals
            if len(names) != 6 or len(additions) != 12:
                raise ValueError('American wave must retain six mutually exclusive model pairs')
            american.append({'event': key, 'action': action_index, 'site': site,
                             'names': sorted(names), 'conditional_additions': len(additions),
                             'conditional_heals': len(heals), 'manpower': 78})
        e.desc += (' Newly formed reserves enter at their allowed maximum strength; '
                   'organisation follows ordinary deployment and later losses still apply.')
    REPORT.update(applied=True, deliveries=deliveries, divisions=len(all_names),
                  american=american, american_max_actual_divisions=12,
                  american_conditional_division_commands=sum(r['conditional_additions'] for r in american))
    return REPORT
