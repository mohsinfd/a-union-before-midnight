def apply_to_bytes(original):
    import aubm_liberator_v2 as v2
    prefix = original.split(MARKER.encode('ascii'),1)[0]
    if MARKER.encode('ascii') not in original:
        prefix += b'\n' if prefix.endswith(b'\n') else b'\n\n'
    return v2.patch_legacy(prefix) + render().encode('ascii')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    before = OUTPUT.read_bytes()
    after = apply_to_bytes(before)
    if args.check:
        if before != after: raise SystemExit('STALE: LIBERATOR3 generated events')
        print('OK: LIBERATOR3 event pack is current')
    else:
        OUTPUT.write_bytes(after)
        print('WROTE: LIBERATOR3 suffix and seven scoped legacy event revisions')


if __name__ == '__main__': main()
