def liberation(r): return f'flag = ind_aubm_sea_land_{r.key}_liberated'


def release_gate(r, owner):
    provinces = tuple(dict.fromkeys(r.minimum + r.hubs))
    complete = all_of(no(f'exists = {r.tag}'),
        *(owned(p, owner) for p in provinces),
        *(friendly_control(p, owner) for p in provinces))
    existing = all_of(puppet(r.tag, owner), *(owned(p, r.tag) for p in r.hubs),
                      *(friendly_control(p, r.tag) for p in r.hubs))
    return all_of(ACTIVE, flag('japan_war'), liberation(r), f'exists = {owner}',
                  no(war(owner)), no(f'alliance = {{ country = {owner} country = JAP }}'),
                  any_of(complete, existing))


def partner_gate(r):
    return all_of(ACTIVE, flag('japan_war'), liberation(r), independent(r.tag),
                  *(owned(p, r.tag) for p in r.hubs), *(friendly_control(p, r.tag) for p in r.hubs))


