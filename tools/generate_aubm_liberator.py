@dataclass(frozen=True)
class Action:
    name: str
    commands: tuple[str, ...] = ()
    gate: str = ''
    chance: int | None = None


def action(name, *commands, gate='', chance=None): return Action(name, commands, gate, chance)
CANCEL = action('Cancel - close without changes')


def event(eid, name, desc, actions, *, gate='', decision=False, country='IND', offset=2, automatic=False, save_date=False):
    lines = ['event = {', f'\tid = {eid}', '\trandom = no', '\tpersistent = yes', f'\tcountry = {country}']
    if automatic: lines.append('\tone_action = yes')
    if save_date: lines.append('\tsave_date = yes')
    if decision:
        lines += [f'\tdecision = {{ {HUMAN} {gate} }}', f'\ttrigger = {{ {HUMAN} {gate} }}']
    elif gate:
        lines.append(f'\ttrigger = {{ {gate} }}')
    lines += [f'\tname = "{name}"', f'\tdesc = "{desc}"', '\tstyle = 2', f'\tpicture = "{PICTURE}"']
    if gate:
        lines += ['\tdate = { day = 0 month = january year = 1940 }', f'\toffset = {offset}', '\tdeathdate = { day = 29 month = december year = 1964 }']
    for index, a in enumerate(actions):
        # DH 1.05.2 accepts the four legacy names action_a-d only. Additional
        # buttons use repeatable plain `action` blocks, NOT action_e, action_f...
        key = f'action_{chr(97 + index)}' if index < 4 else 'action'
        lines += [f'\t{key} = {{']
        if a.gate: lines.append(f'\t\ttrigger = {{ {a.gate} }}')
        if a.chance is not None: lines.append(f'\t\tai_chance = {a.chance}')
        lines.append(f'\t\tname = "{a.name}"')
        for c in a.commands:
            # Conditional commands carry their trigger outside the type clause.
            lines.append(f'\t\tcommand = {{ {c if c.startswith("trigger =") else "type = " + c} }}')
        lines.append('\t}')
    return '\n'.join(lines + ['}'])


