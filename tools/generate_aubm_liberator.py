def flag(key): return f'flag = {P}{key}'
def no(expr): return f'NOT = {{ {expr} }}'
def all_of(*xs): return 'AND = { ' + ' '.join(xs) + ' }'
def any_of(*xs): return 'OR = { ' + ' '.join(xs) + ' }'
def war(tag): return f'war = {{ country = IND country = {tag} }}'
def control(prov, tag): return f'control = {{ province = {prov} data = {tag} }}'
